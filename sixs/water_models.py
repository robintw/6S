def clearw(r=None):
    """
    Get clear water reflectance spectrum.

    Returns spectral reflectance for clear ocean water. Values are provided
    between 0.5 and 1.0 microns based on measurements. Outside this interval,
    values are set to 0.

    Parameters
    ----------
    r : ndarray, optional
        Output array, shape (1501,). If not provided, a new array is created.

    Returns
    -------
    ndarray
        Water reflectance spectrum, shape (1501,)

    Notes
    -----
    Converted from Fortran CLEARW.f

    The spectral sampling covers wavelengths from 0.25 to 4.0 µm with
    1501 equally-spaced points.
    """
    if r is None:
        r = np.empty(1501, dtype=np.float64)

    r[:] = _CLEARW_DATA
    return r


def lakew(r=None):
    """
    Get lake water reflectance spectrum.

    Returns spectral reflectance for lake water. Values are provided
    between 0.35 and 1.0 microns based on measurements. Outside this interval,
    values are set to 0.

    Parameters
    ----------
    r : ndarray, optional
        Output array, shape (1501,). If not provided, a new array is created.

    Returns
    -------
    ndarray
        Water reflectance spectrum, shape (1501,)

    Notes
    -----
    Converted from Fortran LAKEW.f

    The spectral sampling covers wavelengths from 0.25 to 4.0 µm with
    1501 equally-spaced points.
    """
    if r is None:
        r = np.empty(1501, dtype=np.float64)

    r[:] = _LAKEW_DATA
    return r


def get_wavelength_grid():
    """
    Get the wavelength grid for water reflectance spectra.

    Returns
    -------
    ndarray
        Wavelengths in microns, shape (1501,)
        Range: 0.25 to 4.0 µm with equal spacing
    """
    return np.linspace(0.25, 4.0, 1501)


